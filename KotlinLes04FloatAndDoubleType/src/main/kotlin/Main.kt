fun main () {
    var myNumber = 2.5F
    var mySecondNumber = 2.8

    println("myNumber= $myNumber")
    println("mySecondNumber= $mySecondNumber")

    // Float number
    var floatMinValue : Float = Float.MIN_VALUE;
    var floatMaxValue : Float = Float.MAX_VALUE;
    println("The max value of Float: $floatMaxValue")
    println("The min value of Float: $floatMinValue")

    //  Double number
    var doubleMaxValue : Double = Double.MAX_VALUE;
    var doubleMinValue : Double = Double.MIN_VALUE;

    println("The max of double: $doubleMaxValue")
    println("The min of double: $doubleMinValue")
}